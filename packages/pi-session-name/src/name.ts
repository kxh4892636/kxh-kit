/**
 * Pure naming helpers: turn a raw user input or model reply into a short,
 * clean session title. Kept free of pi APIs so it is easy to unit test.
 * @module @kxh4892636/pi-session-name/name
 */

/** Maximum number of Unicode code points kept in a session name. */
export const MAX_NAME_LENGTH = 13;

/** Characters that only decorate a title, stripped from both ends. */
const WRAPPING_MARKS = /^["'`“”‘’「」『』*_~]+|["'`“”‘’「」『』*_~]+$/gu;

/** Leading markdown noise such as `#`, `-`, `1.` or `>` list markers. */
const LEADING_MARKERS = /^(?:#{1,6}\s*|[-*+]\s+|>\s*|\d+[.)]\s*)+/u;

/** A `标题:` / `title:` style label the model may prepend. */
const TITLE_LABEL = /^(?:标题|名称|title|name)\s*[:：]\s*/iu;

/** Trailing punctuation and separators. */
const TRAILING_PUNCTUATION = /[。．.!！?？,，;；:：、~～\s]+$/u;

/** How much of the first input is sent to the model. */
const MAX_PROMPT_INPUT = 500;

/** Bounded passes that peel quotes/punctuation until the title stops changing. */
const MAX_CLEAN_PASSES = 3;

/** Keep at most `maxLength` Unicode code points, never splitting a character. */
export const truncate = (text: string, maxLength: number = MAX_NAME_LENGTH): string =>
  Array.from(text).slice(0, Math.max(0, maxLength)).join("");

/** Collapse whitespace, strip decorative markdown, quotes and trailing punctuation. */
export const cleanTitle = (raw: string, maxLength: number = MAX_NAME_LENGTH): string => {
  let text = raw.replace(/\s+/gu, " ").trim();
  text = text.replace(LEADING_MARKERS, "");
  text = text.replace(TITLE_LABEL, "");
  // Quotes and punctuation can hide each other (`"标题"。`); peel both until stable.
  for (let pass = 0; pass < MAX_CLEAN_PASSES; pass += 1) {
    const next = text.replace(WRAPPING_MARKS, "").replace(TRAILING_PUNCTUATION, "").trim();
    if (next === text) break;
    text = next;
  }
  return truncate(text, maxLength);
};

/**
 * Names generated by the model may carry a label, quotes or a trailing
 * explanation line; keep only the first non-empty line, then clean it.
 */
export const cleanModelOutput = (raw: string, maxLength: number = MAX_NAME_LENGTH): string => {
  const firstLine =
    raw
      .split(/\r?\n/u)
      .map((line) => line.trim())
      .find((line) => line.length > 0) ?? "";
  return cleanTitle(firstLine, maxLength);
};

/** Deterministic fallback used when no model reply is available. */
export const fallbackName = (input: string, maxLength: number = MAX_NAME_LENGTH): string =>
  cleanTitle(input, maxLength);

/** Prompt asking the model for one short, unadorned session title. */
export const buildNamePrompt = (input: string, maxLength: number = MAX_NAME_LENGTH): string => {
  const request = truncate(input.trim(), MAX_PROMPT_INPUT);
  return [
    "为下面这段用户请求生成一个会话标题。",
    `要求：只输出标题本身，不要引号、标点、编号或解释；尽量使用中文；不超过 ${maxLength} 个字。`,
    "",
    "用户请求：",
    request,
  ].join("\n");
};

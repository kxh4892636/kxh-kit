export const OTHER = "其他";

// 返回 [{ name, questions }]，空分组不出现，「其他」固定最后。
export function classify(tagName, questions) {
  const groups = (GROUPS[tagName] ?? []).map((group) => ({ name: group.name, questions: [] }));
  const other = [];
  for (const question of questions) {
    const text = question.text.toLowerCase();
    const hit = (GROUPS[tagName] ?? []).findIndex((group) =>
      group.keywords.some((keyword) => text.includes(keyword)),
    );
    if (hit === -1) other.push(question);
    else groups[hit].questions.push(question);
  }
  const result = groups.filter((group) => group.questions.length > 0);
  if (other.length > 0) result.push({ name: OTHER, questions: other });
  return result;
}
